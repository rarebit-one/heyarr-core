// TestParityVectors mints (or, with -update, rewrites) the four vector files. It
// is the single source of truth for the Kotlin port's fixtures.
func TestParityVectors(t *testing.T) {
	for _, tc := range []struct {
		file string
		gen  func(*testing.T) vectorFile
	}{
		{"playlist.json", playlistVectors},
		{"starred.json", starredVectors},
		{"readingpos.json", readingposVectors},
		{"history.json", historyVectors},
	} {
		t.Run(tc.file, func(t *testing.T) {
			got := indent(t, tc.gen(t))
			testutil.Golden(t, vectorsPath(tc.file), got)
		})
	}
}

// TestParityFoldConvergesToTheVector re-reads each committed file and proves the
// fold of its `changes` reproduces its `encode` and `snapshot` — the exact
// assertion the Kotlin port makes, run against the same bytes so a drift in Go
// and a drift in the port are caught by the same file.
func TestParityFoldConvergesToTheVector(t *testing.T) {
	replay(t, "playlist.json", func(t *testing.T, v wireVector) (string, string) {
		st := crdt.New()
		for _, r := range v.Changes {
			var ch crdt.Change
			mustUnmarshal(t, r, &ch)
			st.Apply(ch)
		}
		return st.Encode(), mustSnap(t, st.Snapshot)
	})
	replay(t, "starred.json", func(t *testing.T, v wireVector) (string, string) {
		s := crdt.NewStarSet()
		for _, r := range v.Changes {
			var ch crdt.StarChange
			mustUnmarshal(t, r, &ch)
			s.Apply(ch)
		}
		return s.Encode(), mustSnap(t, s.Snapshot)
	})
	replay(t, "readingpos.json", func(t *testing.T, v wireVector) (string, string) {
		r := crdt.NewReadingPositions()
		for _, raw := range v.Changes {
			var ch crdt.PositionChange
			mustUnmarshal(t, raw, &ch)
			r.Apply(ch)
		}
		return r.Encode(), mustSnap(t, r.Snapshot)
	})
	replay(t, "history.json", func(t *testing.T, v wireVector) (string, string) {
		l := crdt.NewPlayLog()
		for _, raw := range v.Changes {
			var ch crdt.PlayChange
			mustUnmarshal(t, raw, &ch)
			l.Apply(ch)
		}
		return l.Encode(), mustSnap(t, l.Snapshot)
	})
}

// TestParitySnapshotRoundTrips proves each vector's `snapshot` string decodes
// back to a state whose Encode equals the vector's `encode` — the snapshot decoder
// the port must also match.
func TestParitySnapshotRoundTrips(t *testing.T) {
	roundTrip(t, "playlist.json", func(t *testing.T, b []byte) string {
		st, err := crdt.FromSnapshot(b)
		if err != nil {
			t.Fatal(err)
		}
		return st.Encode()
	})
	roundTrip(t, "starred.json", func(t *testing.T, b []byte) string {
		s, err := crdt.StarSetFromSnapshot(b)
		if err != nil {
			t.Fatal(err)
		}
		return s.Encode()
	})
	roundTrip(t, "readingpos.json", func(t *testing.T, b []byte) string {
		r, err := crdt.ReadingPositionsFromSnapshot(b)
		if err != nil {
			t.Fatal(err)
		}
		return r.Encode()
	})
	roundTrip(t, "history.json", func(t *testing.T, b []byte) string {
		l, err := crdt.PlayLogFromSnapshot(b)
		if err != nil {
			t.Fatal(err)
		}
		return l.Encode()
	})
}

// --- helpers ------------------------------------------------------------------

func replay(t *testing.T, file string, fold func(*testing.T, wireVector) (string, string)) {
	t.Helper()
	vf := loadVectorFile(t, file)
	for _, v := range vf.Vectors {
		t.Run(vf.Kind+"/"+v.Name, func(t *testing.T) {
			gotEncode, gotSnap := fold(t, v)
			if gotEncode != v.Encode {
				t.Errorf("encode mismatch\n--- want ---\n%s\n--- got ---\n%s", v.Encode, gotEncode)
			}
			if gotSnap != v.Snapshot {
				t.Errorf("snapshot mismatch\n--- want ---\n%s\n--- got ---\n%s", v.Snapshot, gotSnap)
			}
		})
	}
}

func roundTrip(t *testing.T, file string, decode func(*testing.T, []byte) string) {
	t.Helper()
	vf := loadVectorFile(t, file)
	for _, v := range vf.Vectors {
		t.Run(vf.Kind+"/"+v.Name, func(t *testing.T) {
			if decode(t, []byte(v.Snapshot)) != v.Encode {
				t.Errorf("snapshot did not round-trip to the vector's encode for %q", v.Name)
			}
		})
	}
}

func loadVectorFile(t *testing.T, file string) vectorFile {
	t.Helper()
	raw, err := os.ReadFile(filepath.Clean(vectorsPath(file)))
	if err != nil {
		t.Fatalf("read %s: %v (run with -update to create it)", file, err)
	}
	var vf vectorFile
	if err := json.Unmarshal(raw, &vf); err != nil {
		t.Fatalf("decode %s: %v", file, err)
	}
	return vf
}

func mustMarshal(t *testing.T, v any) json.RawMessage {
	t.Helper()
	b, err := json.Marshal(v)
	if err != nil {
		t.Fatalf("marshal change: %v", err)
	}
	return b
}

func mustUnmarshal(t *testing.T, raw json.RawMessage, into any) {
	t.Helper()
	if err := json.Unmarshal(raw, into); err != nil {
		t.Fatalf("unmarshal change: %v", err)
	}
}

func mustSnap(t *testing.T, f func() ([]byte, error)) string {
	t.Helper()
	b, err := f()
	if err != nil {
		t.Fatalf("snapshot: %v", err)
	}
	return string(b)
}

func indent(t *testing.T, vf vectorFile) []byte {
	t.Helper()
	b, err := json.MarshalIndent(vf, "", "  ")
	if err != nil {
		t.Fatalf("indent vectors: %v", err)
	}
	return append(b, '\n')
}
