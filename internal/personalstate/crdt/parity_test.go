package crdt_test

// parity_test.go mints CROSS-LANGUAGE PARITY VECTORS for the four personal-state
// CRDTs (§42, §43, #386). Each vector is a sequence of wire changes — exactly the
// bytes json.Marshal(change) produces, which is what statesync encrypts and a peer
// stores opaque — paired with the deterministic State.Encode() the fold converges
// to and the exact Snapshot() bytes it serialises to.
//
// The vectors are the contract a NON-Go client (the Android app, heyarr-mobile)
// ports the merge logic against: it decodes the same `changes`, folds them, and
// must produce the byte-identical `encode` and `snapshot`. There is nothing Go-
// specific in a vector — it is JSON in, a deterministic string out — so a Kotlin
// port that disagrees on one byte has a real divergence, not a "flaky" one.
//
// Regenerate with:  go test ./internal/personalstate/crdt -run TestParityVectors -update
// and re-copy the testdata/vectors/*.json files into heyarr-mobile's test
// resources (the same discipline internal/deviceauth uses for the voidbind-go
// membership vectors).
//
// The fold is a semilattice join, so the converged state is order-independent
// (§43). The vectors carry the changes in one order; TestParityFoldIsOrderFree
// proves reversing them changes neither Encode nor Snapshot, which is the property
// the Kotlin port must also hold — so the vectors do double duty as a Go self-check.

import (
	"encoding/json"
	"math"
	"os"
	"path/filepath"
	"testing"

	"github.com/rarebit-one/heyarr-core/internal/personalstate/crdt"
	"github.com/rarebit-one/heyarr-core/internal/testutil"
)

// A wireVector is one named scenario: the changes on the wire, the Encode() the
// fold converges to, and the exact Snapshot() bytes (as a JSON string, since the
// snapshot is itself JSON) so a port validates its snapshot encoder AND decoder.
type wireVector struct {
	Name     string            `json:"name"`
	Changes  []json.RawMessage `json:"changes"`
	Encode   string            `json:"encode"`
	Snapshot string            `json:"snapshot"`
}

type vectorFile struct {
	Kind    string       `json:"kind"`
	Note    string       `json:"note"`
	Vectors []wireVector `json:"vectors"`
}

const vectorNote = "Cross-language parity vectors. Generated by heyarr-core " +
	"internal/personalstate/crdt parity_test.go (-update); do not hand-edit. " +
	"`changes` are the exact json.Marshal(change) wire form; a port decodes them, " +
	"folds them, and must reproduce `encode` and `snapshot` byte-for-byte."

func vectorsPath(name string) string { return filepath.Join("testdata", "vectors", name) }

// maxU64 is math.MaxUint64 — the Lamport-clock poison value a saturating
// increment must handle. It is in the vectors deliberately: a port that stores
// the counter in a signed 64-bit integer overflows here, and the mismatch says so.
const maxU64 = uint64(math.MaxUint64)

// --- playlist -----------------------------------------------------------------

func playlistVectors(t *testing.T) vectorFile {
	t.Helper()
	ord := func(c uint64, tag string) crdt.OrderKey { return crdt.OrderKey{Counter: c, Tag: crdt.Tag(tag)} }
	add := func(item, tag string, o crdt.OrderKey) crdt.Change {
		return crdt.Change{Op: crdt.OpAdd, ItemID: item, Tag: crdt.Tag(tag), Order: o}
	}
	rm := func(item string, observed ...string) crdt.Change {
		obs := make([]crdt.Tag, len(observed))
		for i, o := range observed {
			obs[i] = crdt.Tag(o)
		}
		return crdt.Change{Op: crdt.OpRemove, ItemID: item, Observed: obs}
	}
	scenarios := []struct {
		name    string
		changes []crdt.Change
	}{
		{"empty", nil},
		{"single-add", []crdt.Change{add("a", "t1", ord(1, "t1"))}},
		{"ordered-adds", []crdt.Change{
			add("a", "t1", ord(1, "t1")), add("b", "t2", ord(2, "t2")), add("c", "t3", ord(3, "t3")),
		}},
		{"lamport-tiebreak-same-counter", []crdt.Change{
			add("b", "t2", ord(5, "t2")), add("a", "t1", ord(5, "t1")),
		}},
		{"add-wins-concurrent-add-survives-remove", []crdt.Change{
			add("a", "t1", ord(1, "t1")),
			add("a", "t2", ord(2, "t2")),
			rm("a", "t1"), // the remove only observed t1; t2 survives → a is still present
		}},
		{"remove-tombstones-all-observed", []crdt.Change{
			add("a", "t1", ord(1, "t1")), rm("a", "t1"),
		}},
		{"same-item-two-adds-smallest-order-wins-position", []crdt.Change{
			add("a", "t3", ord(9, "t3")), add("a", "t1", ord(2, "t1")),
		}},
		{"counter-poison-saturates-at-maxuint64", []crdt.Change{
			add("a", "t1", ord(1, "t1")), add("b", "t2", ord(maxU64, "t2")),
		}},
	}
	vf := vectorFile{Kind: "playlist", Note: vectorNote}
	for _, sc := range scenarios {
		st := crdt.New()
		raw := make([]json.RawMessage, 0, len(sc.changes))
		for _, ch := range sc.changes {
			raw = append(raw, mustMarshal(t, ch))
		}
		st.Apply(sc.changes...)
		vf.Vectors = append(vf.Vectors, wireVector{
			Name: sc.name, Changes: raw, Encode: st.Encode(), Snapshot: mustSnap(t, st.Snapshot),
		})
	}
	return vf
}

// --- starred ------------------------------------------------------------------

func starredVectors(t *testing.T) vectorFile {
	t.Helper()
	star := func(item, tag string, at uint64) crdt.StarChange {
		return crdt.StarChange{Op: crdt.OpStar, ItemID: item, Tag: crdt.StarTag(tag), At: at}
	}
	unstar := func(item string, observed ...string) crdt.StarChange {
		obs := make([]crdt.StarTag, len(observed))
		for i, o := range observed {
			obs[i] = crdt.StarTag(o)
		}
		return crdt.StarChange{Op: crdt.OpUnstar, ItemID: item, Observed: obs}
	}
	scenarios := []struct {
		name    string
		changes []crdt.StarChange
	}{
		{"empty", nil},
		{"single-star", []crdt.StarChange{star("a", "s1", 1)}},
		{"recency-order-desc", []crdt.StarChange{star("a", "s1", 1), star("b", "s2", 2)}},
		{"add-wins-concurrent-star-survives-unstar", []crdt.StarChange{
			star("a", "s1", 1), star("a", "s2", 2), unstar("a", "s1"),
		}},
		{"unstar-tombstones-all-observed", []crdt.StarChange{star("a", "s1", 1), unstar("a", "s1")}},
		{"counter-poison-saturates-at-maxuint64", []crdt.StarChange{
			star("a", "s1", 1), star("b", "s2", maxU64),
		}},
	}
	vf := vectorFile{Kind: "starred", Note: vectorNote}
	for _, sc := range scenarios {
		s := crdt.NewStarSet()
		raw := make([]json.RawMessage, 0, len(sc.changes))
		for _, ch := range sc.changes {
			raw = append(raw, mustMarshal(t, ch))
		}
		s.Apply(sc.changes...)
		vf.Vectors = append(vf.Vectors, wireVector{
			Name: sc.name, Changes: raw, Encode: s.Encode(), Snapshot: mustSnap(t, s.Snapshot),
		})
	}
	return vf
}

// --- reading positions --------------------------------------------------------

func readingposVectors(t *testing.T) vectorFile {
	t.Helper()
	set := func(pub, pos string, at uint64, writer string) crdt.PositionChange {
		return crdt.PositionChange{PubID: pub, Position: pos, At: at, Writer: crdt.PosTag(writer)}
	}
	scenarios := []struct {
		name    string
		changes []crdt.PositionChange
	}{
		{"empty", nil},
		{"single-position", []crdt.PositionChange{set("b1", "epubcfi(/6/4!/4/2)", 1, "w1")}},
		{"lww-later-write-wins", []crdt.PositionChange{
			set("b1", "p1", 1, "w1"), set("b1", "p2", 2, "w2"),
		}},
		{"lww-concurrent-lower-writer-loses", []crdt.PositionChange{
			set("b1", "p2", 2, "w2"), set("b1", "p0", 2, "w1"), // same At; w2 > w1 wins → p2
		}},
		{"tie-break-on-position-string", []crdt.PositionChange{
			set("b1", "aaa", 5, "w9"), set("b1", "bbb", 5, "w9"), // fully tied key → greater position wins → bbb
		}},
		{"go-quoting-escapes", []crdt.PositionChange{
			set("b1", "a\"b\\c\td\ne", 1, "w1"), // exercises strconv.Quote parity in %q
		}},
		{"two-publications-sorted", []crdt.PositionChange{
			set("b2", "x", 1, "w1"), set("b1", "y", 2, "w2"),
		}},
		{"counter-poison-saturates-at-maxuint64", []crdt.PositionChange{
			set("b1", "p", maxU64, "w1"),
		}},
	}
	vf := vectorFile{Kind: "readingpos", Note: vectorNote}
	for _, sc := range scenarios {
		r := crdt.NewReadingPositions()
		raw := make([]json.RawMessage, 0, len(sc.changes))
		for _, ch := range sc.changes {
			raw = append(raw, mustMarshal(t, ch))
		}
		r.Apply(sc.changes...)
		vf.Vectors = append(vf.Vectors, wireVector{
			Name: sc.name, Changes: raw, Encode: r.Encode(), Snapshot: mustSnap(t, r.Snapshot),
		})
	}
	return vf
}

