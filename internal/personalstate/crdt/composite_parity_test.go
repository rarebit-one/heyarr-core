package crdt_test

// composite_parity_test.go mints the CROSS-LANGUAGE PARITY VECTORS for ADR-0113
// §6's composite snapshot (composite_snapshot.go): the first client to snapshot a
// space holding more than one kind pins the shape here. Each vector gives the
// folded kinds' snapshot bytes (`states`, built by folding real changes, so they
// are each kind's canonical bytes) and the plaintexts the writer could not fold
// (`verbatim`, deliberately unsorted). A port builds the composite from them and
// must reproduce `snapshot` byte-for-byte, then read it back to the same parts.
//
// Regenerate with:  go test ./internal/personalstate/crdt -run TestCompositeParityVectors -update
// and re-copy testdata/vectors/composite.json into the Kotlin clients' test resources.

import (
	"bytes"
	"encoding/json"
	"testing"

	"github.com/rarebit-one/heyarr-core/internal/personalstate/crdt"
	"github.com/rarebit-one/heyarr-core/internal/testutil"
)

type compositeVector struct {
	Name     string            `json:"name"`
	States   map[string]string `json:"states"`
	Verbatim []string          `json:"verbatim"`
	Snapshot string            `json:"snapshot"`
}

type compositeVectorFile struct {
	Kind    string            `json:"kind"`
	Note    string            `json:"note"`
	Vectors []compositeVector `json:"vectors"`
}

const compositeNote = "Cross-language parity vectors for the ADR-0113 §6 composite snapshot. Generated by " +
	"heyarr-core internal/personalstate/crdt composite_parity_test.go (-update); do not hand-edit. " +
	"`states` are each folded kind's own snapshot bytes; `verbatim` the plaintexts the writer could not " +
	"fold, in no particular order. A port builds the composite from them and must reproduce `snapshot` " +
	"byte-for-byte: states keyed and ordered by kind, verbatim base64 and ordered by plaintext bytes."

// compositeDriveState folds drive changes given as wire JSON and returns the drive's snapshot.
func compositeDriveState(t *testing.T, wire ...string) string {
	t.Helper()
	d := crdt.NewDrive()
	for _, w := range wire {
		var c crdt.DriveChange
		if err := json.Unmarshal([]byte(w), &c); err != nil {
			t.Fatal(err)
		}
		d.Apply(c)
	}
	b, err := d.Snapshot()
	if err != nil {
		t.Fatal(err)
	}
	return string(b)
}

