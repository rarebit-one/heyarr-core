func TestCompositeParityVectors(t *testing.T) {
	// A path with characters encoding/json escapes ('&', '<'), so a port pins that
	// the embedded state is carried byte-for-byte, not re-encoded.
	drive := compositeDriveState(t,
		driveWire(crdt.KindDrive, 0, "Docs/a&b <draft>.txt", vecBlob("a1"), 100, 1_700_000_000, "", 1, "w1", 0, ""),
		driveWire(crdt.KindDrive, 0, "Photos/x.jpg", vecBlob("b2"), 2048, 1_700_000_100,
			`"mime":"image/jpeg","thumbnail":"`+vecBlob("e1")+`"`, 2, "w2", 0, ""),
	)
	albumCreate := `{"k":"album","op":0,"album_id":"alb","title":"Trip","at":3,"writer":"w3","base":{}}`
	albums := compositeAlbumState(t, albumCreate)
	policy := `{"k":"policy","device":"x25519:aa","spaces":{"s1":{"mode":"full"}},"at":4,"writer":"w4"}`
	futureOp := `{"k":"drive","op":42,"path":"Docs/c.txt","at":5,"writer":"w5"}`
	newerKind := `{"k":"note","body":"from a newer kind","at":6,"writer":"w6"}`

	cases := []struct {
		name     string
		states   map[string]string
		verbatim []string
	}{
		{
			"a-drive-writer-carries-albums-and-policy-verbatim",
			map[string]string{crdt.KindDrive: drive},
			[]string{policy, futureOp, albumCreate},
		},
		{
			"a-writer-that-folds-drive-and-albums",
			map[string]string{crdt.KindDrive: drive, crdt.KindAlbum: albums},
			[]string{newerKind, policy},
		},
		{"nothing-left-unfolded", map[string]string{crdt.KindDrive: drive}, []string{}},
		{"only-verbatim", map[string]string{}, []string{futureOp, policy}},
	}

	var vectors []compositeVector
	for _, in := range cases {
		c := crdt.Composite{States: map[string][]byte{}}
		for k, s := range in.states {
			c.States[k] = []byte(s)
		}
		for _, v := range in.verbatim {
			c.Verbatim = append(c.Verbatim, []byte(v))
		}
		snap, err := c.Snapshot()
		if err != nil {
			t.Fatalf("%s: %v", in.name, err)
		}
		// Round trip: the same parts come back, verbatim in plaintext-byte order.
		back, err := crdt.CompositeFromSnapshot(snap)
		if err != nil {
			t.Fatalf("%s: %v", in.name, err)
		}
		for k, s := range in.states {
			if string(back.States[k]) != s {
				t.Fatalf("%s: state %s did not round-trip", in.name, k)
			}
		}
		if len(back.States) != len(in.states) || len(back.Verbatim) != len(in.verbatim) {
			t.Fatalf("%s: parts lost in the round trip", in.name)
		}
		for i := 1; i < len(back.Verbatim); i++ {
			if bytes.Compare(back.Verbatim[i-1], back.Verbatim[i]) > 0 {
				t.Fatalf("%s: verbatim not in byte order", in.name)
			}
		}
		vectors = append(vectors, compositeVector{Name: in.name, States: in.states, Verbatim: in.verbatim, Snapshot: string(snap)})
	}

	buf, err := json.MarshalIndent(compositeVectorFile{Kind: crdt.KindComposite, Note: compositeNote, Vectors: vectors}, "", "  ")
	if err != nil {
		t.Fatal(err)
	}
	testutil.Golden(t, "testdata/vectors/composite.json", append(buf, '\n'))
}

// TestASingleKindReaderRefusesAComposite: a composite decoded as one kind's
// snapshot would read as an empty state (unknown fields are ignored) and hide
// what compaction removed, so every single-kind reader refuses it.
func TestASingleKindReaderRefusesAComposite(t *testing.T) {
	snap, err := crdt.Composite{States: map[string][]byte{crdt.KindDrive: []byte(`{"entries":[],"counter":0}`)}}.Snapshot()
	if err != nil {
		t.Fatal(err)
	}
	if _, err := crdt.DriveFromSnapshot(snap); err == nil {
		t.Error("DriveFromSnapshot read a composite")
	}
	if _, err := crdt.AlbumsFromSnapshot(snap); err == nil {
		t.Error("AlbumsFromSnapshot read a composite")
	}
	if _, err := crdt.FromSnapshot(snap); err == nil {
		t.Error("FromSnapshot read a composite")
	}
	if crdt.IsPlaylistSnapshot(snap) {
		t.Error("a composite passed as a playlist snapshot")
	}
	if !crdt.IsCompositeSnapshot(snap) || crdt.IsCompositeSnapshot([]byte(`{"entries":[],"counter":0}`)) {
		t.Error("IsCompositeSnapshot misread")
	}
}

// TestACompositeRefusesWhatItCannotCarry: a state that is not JSON, or one
// filed under no kind or under the composite tag itself, is refused; so is a
// composite of another version.
func TestACompositeRefusesWhatItCannotCarry(t *testing.T) {
	for name, c := range map[string]crdt.Composite{
		"not-json":   {States: map[string][]byte{crdt.KindDrive: []byte("{")}},
		"no-kind":    {States: map[string][]byte{"": []byte("{}")}},
		"nested-tag": {States: map[string][]byte{crdt.KindComposite: []byte("{}")}},
	} {
		if _, err := c.Snapshot(); err == nil {
			t.Errorf("%s: accepted", name)
		}
	}
	if _, err := crdt.CompositeFromSnapshot([]byte(`{"k":"composite","v":2,"states":{},"verbatim":[]}`)); err == nil {
		t.Error("a version-2 composite was read")
	}
}
