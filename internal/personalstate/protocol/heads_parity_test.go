package protocol_test

// heads_parity_test.go mints CROSS-LANGUAGE PARITY VECTORS for [protocol.Heads]:
// the causal frontier a device parents its next change on (ADR-0101). A Kotlin
// device keeps the heads INCREMENTALLY over the log it has pulled (it never holds
// the whole log), so each vector lists a log in the order a device would pull it,
// and a port must reach `heads` both by folding the changes one at a time in that
// order and over the whole set at once.
//
// The logs cover what a pulled log really looks like: a flat history (every
// change a root, as devices wrote before ADR-0101), a chain, a fork and its merge,
// a child pulled before its parent (replication did not push parents first before
// #682), a change naming a parent that is no longer a head, and a parent the log
// does not hold (compacted away, or not pulled yet).
//
// Regenerate with:  go test ./internal/personalstate/protocol -run TestHeadsParityVectors -update
// and re-copy testdata/vectors/heads.json into the Kotlin clients' test resources.

import (
	"encoding/json"
	"fmt"
	"sort"
	"testing"

	"github.com/rarebit-one/heyarr-core/internal/personalstate/protocol"
	"github.com/rarebit-one/heyarr-core/internal/testutil"
)

type headsChange struct {
	ChangeID string   `json:"change_id"`
	Parents  []string `json:"parents"`
}

type headsVector struct {
	Name  string        `json:"name"`
	Log   []headsChange `json:"log"`
	Heads []string      `json:"heads"`
}

type headsVectorFile struct {
	Note    string        `json:"note"`
	Vectors []headsVector `json:"vectors"`
}

const headsNote = "Cross-language parity vectors for protocol.Heads, the causal frontier a device parents " +
	"its next change on (ADR-0101). Generated by heyarr-core internal/personalstate/protocol " +
	"heads_parity_test.go (-update); do not hand-edit. `log` is in pull order; a port must reach " +
	"`heads` (sorted) both folding the log one change at a time in that order and over the whole set."

func TestHeadsParityVectors(t *testing.T) {
	n := 0
	change := func(parents ...string) protocol.EncryptedChange {
		t.Helper()
		n++
		c, err := protocol.NewChange("space-heads", parents, []byte(fmt.Sprintf("opaque-%d", n)))
		if err != nil {
			t.Fatal(err)
		}
		return c
	}
	logOf := func(cs ...protocol.EncryptedChange) []protocol.EncryptedChange { return cs }

	r1, r2, r3 := change(), change(), change()
	a := change()
	b := change(a.ChangeID)
	c := change(b.ChangeID)
	left := change(a.ChangeID)
	right := change(a.ChangeID)
	merge := change(left.ChangeID, right.ChangeID)
	stale := change(a.ChangeID) // names a, which b has already superseded
	gone := "blake3:" + fmt.Sprintf("%064x", 0)
	orphan := change(gone)
	first := change(r1.ChangeID, r2.ChangeID, r3.ChangeID)

	cases := []struct {
		name string
		log  []protocol.EncryptedChange
	}{
		{"empty", nil},
		{"flat-history-is-all-heads", logOf(r3, r1, r2)},
		{"a-chain-has-one-head", logOf(a, b, c)},
		{"a-fork-has-two-heads", logOf(a, left, right)},
		{"a-merge-closes-the-fork", logOf(a, left, right, merge)},
		{"a-child-pulled-before-its-parent", logOf(c, b, a)},
		{"naming-a-superseded-change", logOf(a, b, stale)},
		{"a-parent-the-log-does-not-hold", logOf(orphan)},
		{"the-first-parented-write-on-a-flat-history", logOf(r1, r2, r3, first)},
		{"everything-out-of-order", logOf(merge, first, right, r2, stale, a, r3, left, b, r1)},
	}

	var vectors []headsVector
	for _, in := range cases {
		v := headsVector{Name: in.name, Log: []headsChange{}, Heads: protocol.Heads(in.log)}
		if v.Heads == nil {
			v.Heads = []string{}
		}
		for _, ch := range in.log {
			parents := ch.Parents
			if parents == nil {
				parents = []string{}
			}
			v.Log = append(v.Log, headsChange{ChangeID: ch.ChangeID, Parents: parents})
		}
		vectors = append(vectors, v)
	}

	buf, err := json.MarshalIndent(headsVectorFile{Note: headsNote, Vectors: vectors}, "", "  ")
	if err != nil {
		t.Fatal(err)
	}
	testutil.Golden(t, "testdata/vectors/heads.json", append(buf, '\n'))

	// The committed answers are Heads' own; pin the cases whose answer is known by
	// construction, so a regression in Heads cannot regenerate itself green.
	want := map[string][]string{
		"flat-history-is-all-heads":                  sorted(r1.ChangeID, r2.ChangeID, r3.ChangeID),
		"a-chain-has-one-head":                       {c.ChangeID},
		"a-fork-has-two-heads":                       sorted(left.ChangeID, right.ChangeID),
		"a-merge-closes-the-fork":                    {merge.ChangeID},
		"a-child-pulled-before-its-parent":           {c.ChangeID},
		"naming-a-superseded-change":                 sorted(b.ChangeID, stale.ChangeID),
		"a-parent-the-log-does-not-hold":             {orphan.ChangeID},
		"the-first-parented-write-on-a-flat-history": {first.ChangeID},
	}
	for _, v := range vectors {
		w, ok := want[v.Name]
		if !ok {
			continue
		}
		if fmt.Sprint(v.Heads) != fmt.Sprint(w) {
			t.Errorf("%s: Heads = %v, want %v", v.Name, v.Heads, w)
		}
	}
}

func sorted(ids ...string) []string {
	out := append([]string(nil), ids...)
	sort.Strings(out)
	return out
}
