#!/usr/bin/env bash
# Write THIRD_PARTY_LICENSES.txt: the licence and notice texts of every module
# compiled into the released binaries, plus the Go standard library.
#
# A static binary carries its dependencies, so redistributing it carries their
# notice obligations too: MIT/BSD ask for the copyright and licence text with
# binary copies, and Apache-2.0 §4(d) asks for the NOTICE file where one exists.
# goreleaser runs this as a before-hook and ships the file in every archive and
# in the image (/usr/share/doc/heyarr/).
#
# The module list comes from `go list -deps` over the binaries' main packages,
# so it is what is linked, not everything go.mod mentions. Our own modules
# (github.com/rarebit-one/*) are listed but carry no third-party text.
# A third-party module with no licence file fails the run: shipping it without
# knowing its terms is the thing this exists to prevent.
#
# Usage: scripts/third-party-licenses.sh [OUT]   (default THIRD_PARTY_LICENSES.txt)
set -euo pipefail
cd "$(dirname "$0")/.."
OUT=${1:-THIRD_PARTY_LICENSES.txt}
MAINS=(./cmd/heyarr ./cmd/mnemosyne)
OWN='github.com/rarebit-one/'

modules=$(go list -deps -f '{{with .Module}}{{if not .Main}}{{.Path}}	{{.Version}}	{{.Dir}}{{end}}{{end}}' "${MAINS[@]}" | sort -u)
[ -n "$modules" ] || { echo "third-party-licenses: go list found no modules" >&2; exit 1; }

licence_files() { # licence and notice files at the root of a module directory
  find "$1" -maxdepth 1 -type f \( -iname 'LICEN[CS]E*' -o -iname 'COPYING*' -o -iname 'NOTICE*' -o -iname 'PATENTS*' \) | sort
}

tmp=$(mktemp)
trap 'rm -f "$tmp"' EXIT
missing=()
{
  echo "Third-party software in heyarr and mnemosyne"
  echo
  echo "These binaries are statically linked and include the modules below. Each"
  echo "section reproduces that module's licence and notice files as published."
  echo "Generated by scripts/third-party-licenses.sh from \`go list -deps\`."
  echo
  goroot=$(go env GOROOT)
  echo "================================================================================"
  echo "Go standard library and runtime ($(go env GOVERSION))"
  echo "================================================================================"
  for f in "$goroot/LICENSE" "$goroot/PATENTS"; do
    [ -f "$f" ] && { echo "--- $(basename "$f")"; cat "$f"; echo; }
  done
  while IFS=$'\t' read -r path version dir; do
    echo "================================================================================"
    echo "$path $version"
    echo "================================================================================"
    if [[ $path == "$OWN"* ]]; then
      echo "First-party module of the copyright holder of this software; no third-party terms."
      echo
      continue
    fi
    files=$(licence_files "$dir")
    if [ -z "$files" ]; then
      missing+=("$path@$version")
      continue
    fi
    while IFS= read -r f; do
      echo "--- $(basename "$f")"
      cat "$f"
      echo
    done <<<"$files"
  done <<<"$modules"
} >"$tmp"

if [ ${#missing[@]} -gt 0 ]; then
  printf 'third-party-licenses: no licence file in %s\n' "${missing[@]}" >&2
  exit 1
fi
mv "$tmp" "$OUT"
trap - EXIT
echo "third-party-licenses: wrote $OUT ($(grep -c '^================' "$OUT" | awk '{print $1/2}') sections)"
